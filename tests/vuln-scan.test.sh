#!/bin/bash

# Behavior suite for .docket/bin/vuln-scan. Each case builds a throwaway git
# repo under $TMPDIR carrying a committed copy of the script (it scans the
# Cargo.lock of the repo it lives in) and runs it with a stub `curl` first on
# PATH. The stub answers OSV's batch and advisory endpoints from a fixed table,
# so the suite never reaches the network.
#
# Stub table: badcrate 1.0.0 -> RUSTSEC-2099-0001, bumpcrate 2.0.0 ->
# RUSTSEC-2099-0002, newcrate 0.1.0 -> RUSTSEC-2099-0003. Every other
# (crate, version) has no advisory.
#
# Needs git, jq and bash; no engine, no network.

set -uo pipefail

# The engine exports these to gate processes; a suite run under a gate must not
# inherit them, or the unset-base case silently takes the scoped branch.
unset DOCKET_GATE DOCKET_GATE_BASE
if [ -z "${DOCKET_GATE+x}" ] && [ -z "${DOCKET_GATE_BASE+x}" ]; then
    printf 'PASS: %s\n' "suite environment: DOCKET_GATE and DOCKET_GATE_BASE unset"
else
    printf 'FAIL: %s\n' "suite environment: DOCKET_GATE or DOCKET_GATE_BASE inherited from the caller"
    exit 1
fi

SCRIPT_DIR=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
SCANNER="${SCRIPT_DIR}/../.docket/bin/vuln-scan"

fatal() { printf 'FATAL: %s\n' "$1" >&2; exit 2; }
[ -x "$SCANNER" ] || fatal "vuln-scan not executable at ${SCANNER}"
command -v git >/dev/null 2>&1 || fatal "git is required"
command -v jq >/dev/null 2>&1 || fatal "jq is required"

WORK=$(mktemp -d "${TMPDIR:-/tmp}/vuln-scan-test.XXXXXX") || fatal "mktemp failed"
trap 'rm -rf "$WORK"' EXIT

pass=0; fail=0
ok()  { pass=$((pass + 1)); printf 'PASS: %s\n' "$1"; }
bad() { fail=$((fail + 1)); printf 'FAIL: %s\n' "$1"; }

mkdir "$WORK/bin"
cat >"$WORK/bin/curl" <<'STUB'
#!/usr/bin/env bash
# Stub for the two OSV calls vuln-scan makes: POST /v1/querybatch and
# GET /v1/vulns/<id>. Writes the body to -o, prints the HTTP code like -w.
out=""; data=""; url=""
while [ "$#" -gt 0 ]; do
  case "$1" in
    -o) out="$2"; shift 2 ;;
    -w|-H|--max-time) shift 2 ;;
    --data-binary) data="${2#@}"; shift 2 ;;
    -*) shift ;;
    *) url="$1"; shift ;;
  esac
done
table='{"badcrate 1.0.0":"RUSTSEC-2099-0001","bumpcrate 2.0.0":"RUSTSEC-2099-0002","newcrate 0.1.0":"RUSTSEC-2099-0003"}'
case "$url" in
  */v1/querybatch)
    jq --argjson t "$table" \
      '{results: [.queries[] | $t[.package.name + " " + .version] as $id
        | if $id then {vulns: [{id: $id}]} else {} end]}' "$data" >"$out" || exit 1
    ;;
  */v1/vulns/*)
    jq -n --arg id "${url##*/}" '{id: $id, summary: "stub advisory"}' >"$out" || exit 1
    ;;
  *)
    echo "stub curl: unexpected URL '$url'" >&2
    exit 7
    ;;
esac
printf 200
STUB
chmod +x "$WORK/bin/curl"

REGISTRY='registry+https://github.com/rust-lang/crates.io-index'

# lockfile <name> <version> ...: a Cargo.lock holding the workspace's own path
# package plus one registry package per name/version pair.
lockfile() {
    printf '# This file is automatically @generated by Cargo.\nversion = 4\n\n'
    printf '[[package]]\nname = "app"\nversion = "0.1.0"\n'
    while [ "$#" -gt 0 ]; do
        printf '\n[[package]]\nname = "%s"\nversion = "%s"\nsource = "%s"\n' "$1" "$2" "$REGISTRY"
        shift 2
    done
}

# fresh_repo <name> <lockfile-args...>: a repo whose base commit holds the
# scanner, gate-range, and a Cargo.lock built from the arguments. Pass no
# lockfile arguments for a base without Cargo.lock.
fresh_repo() {
    local d="$WORK/$1"
    shift
    mkdir -p "$d/.docket/bin"
    (
        cd "$d" || exit 1
        git init -q
        git config user.email t@example.invalid; git config user.name t
        cp "$SCANNER" .docket/bin/vuln-scan
        cp "${SCRIPT_DIR}/../.docket/bin/gate-range" .docket/bin/gate-range
        printf 'readme\n' > README.md
        if [ "$#" -gt 0 ]; then lockfile "$@" > Cargo.lock; fi
        git add -A && git commit -qm base
    )
    printf '%s' "$d"
}

# commit_lock <repo> <lockfile-args...>: a second commit rewriting Cargo.lock.
commit_lock() {
    local repo="$1"
    shift
    (cd "$repo" && lockfile "$@" > Cargo.lock && git add Cargo.lock && git commit -qm lock)
}

head_of() { git -C "$1" rev-parse HEAD; }

# run_scan <repo> <env...>: runs the copied scanner with the stub first on
# PATH; sets OUT and CODE.
run_scan() {
    local repo="$1"
    shift
    OUT=$(cd "$repo" && env PATH="$WORK/bin:$PATH" "$@" .docket/bin/vuln-scan 2>&1); CODE=$?
}

# preexisting-passes: the base pins a stub-vulnerable crate; the step's commit
# leaves Cargo.lock alone. Scoped to that base, the match is printed, not failed.
repo=$(fresh_repo preexisting badcrate 1.0.0 okcrate 1.0.0)
base=$(head_of "$repo")
(cd "$repo" && printf 'unrelated\n' > NOTES.md && git add NOTES.md && git commit -qm unrelated)
run_scan "$repo" DOCKET_GATE_BASE="$base"
if [ "$CODE" -ne 0 ]; then
    bad "preexisting-passes (want exit 0, got $CODE): $OUT"
elif [[ "$OUT" != *"RUSTSEC-2099-0001"*"badcrate 1.0.0"* ]]; then
    bad "preexisting-passes (exit 0, pre-existing match not printed): $OUT"
else
    ok "preexisting-passes: exit 0 and the pre-existing badcrate 1.0.0 match is printed"
fi

# unset-whole-lockfile: same repo, no base: the whole lockfile is scanned and
# the stub-vulnerable crate fails the gate.
run_scan "$repo"
if [ "$CODE" -eq 1 ] && [[ "$OUT" == *"badcrate 1.0.0"* ]]; then
    ok "unset-whole-lockfile: exit 1 naming badcrate 1.0.0"
else
    bad "unset-whole-lockfile (want exit 1 naming badcrate 1.0.0, got $CODE): $OUT"
fi

# added-fails: the step's commit bumps bumpcrate to a stub-vulnerable version;
# the pre-existing badcrate match does not hide it.
repo=$(fresh_repo added badcrate 1.0.0 bumpcrate 1.0.0)
base=$(head_of "$repo")
commit_lock "$repo" badcrate 1.0.0 bumpcrate 2.0.0
run_scan "$repo" DOCKET_GATE_BASE="$base"
if [ "$CODE" -ne 0 ] && [[ "$OUT" == *"bumpcrate 2.0.0"* ]] && [[ "$OUT" == *"FAILED"* ]]; then
    ok "added-fails: exit $CODE naming bumpcrate 2.0.0"
else
    bad "added-fails (want non-zero naming bumpcrate 2.0.0, got $CODE): $OUT"
fi

# added-entry-fails: the step's commit adds a crate that was not in the base
# lockfile at all, at a stub-vulnerable version.
repo=$(fresh_repo added-entry okcrate 1.0.0)
base=$(head_of "$repo")
commit_lock "$repo" okcrate 1.0.0 newcrate 0.1.0
run_scan "$repo" DOCKET_GATE_BASE="$base"
if [ "$CODE" -eq 1 ] && [[ "$OUT" == *"newcrate 0.1.0"* ]]; then
    ok "added-entry-fails: exit 1 naming newcrate 0.1.0"
else
    bad "added-entry-fails (want exit 1 naming newcrate 0.1.0, got $CODE): $OUT"
fi

# base-without-lockfile-fails: a base tree with no Cargo.lock is an empty
# baseline, so every pinned crate counts as added.
repo=$(fresh_repo no-base-lock)
base=$(head_of "$repo")
commit_lock "$repo" badcrate 1.0.0
run_scan "$repo" DOCKET_GATE_BASE="$base"
if [ "$CODE" -eq 1 ] && [[ "$OUT" == *"badcrate 1.0.0"* ]]; then
    ok "base-without-lockfile-fails: exit 1 naming badcrate 1.0.0"
else
    bad "base-without-lockfile-fails (want exit 1 naming badcrate 1.0.0, got $CODE): $OUT"
fi

# unresolvable-base-fails: a base that names no commit refuses to scan rather
# than reading every match as pre-existing; an option-shaped one never reaches
# git as a flag.
repo="$WORK/preexisting"
run_scan "$repo" DOCKET_GATE_BASE=deadbeef
if [ "$CODE" -ne 0 ] && [[ "$OUT" == *"DOCKET_GATE_BASE"* ]]; then
    ok "unresolvable-base-fails: exit $CODE naming DOCKET_GATE_BASE"
else
    bad "unresolvable-base-fails (want non-zero naming DOCKET_GATE_BASE, got $CODE): $OUT"
fi
run_scan "$repo" DOCKET_GATE_BASE="--output=$WORK/pwn"
if [ "$CODE" -ne 0 ] && [ ! -e "$WORK/pwn" ]; then
    ok "option-shaped-base-fails: exit $CODE and no file written"
else
    bad "option-shaped-base-fails (want non-zero and no $WORK/pwn, got $CODE): $OUT"
fi

printf '\n%d passed, %d failed\n' "$pass" "$fail"
[ "$fail" -eq 0 ]
